const { v4: uuidv4 } = require('uuid');
const EventEmitter = require('events');

/**
 * AgentBrowserTaskQueue
 * 
 * Translates multi-agent outputs into explicit browser action tasks:
 * 
 * Pipeline Architecture:
 * AI Agent -> Agent Output -> Task/Action Object -> Automation Controller -> Browser Controller -> YouTube Studio -> Visible UI Action -> Verification -> Dashboard Status
 */
class AgentBrowserTaskQueue extends EventEmitter {
  constructor(studioController, io = null) {
    super();
    this.studio = studioController;
    this.io = io;
    this.tasks = [];
    this.currentTask = null;
    this.history = [];
    this.isProcessing = false;
    this.confirmationWaitResolve = null;

    // Listen to studio controller actions and forward to WebSocket & listeners
    this.studio.on('action', (actionEvent) => {
      this.emit('action_update', actionEvent);
      if (this.io) {
        this.io.emit('browser:action', actionEvent);
      }
    });

    this.studio.browser.on('log', (logEvent) => {
      this.emit('browser_log', logEvent);
      if (this.io) {
        this.io.emit('browser:log', logEvent);
      }
    });
  }

  /**
   * Enqueue a new browser task from an AI agent
   */
  addTask(agentId, action, target, payload = {}) {
    const task = {
      task_id: `yt_task_${Date.now()}_${Math.floor(Math.random()*1000)}`,
      agent: agentId,
      action,
      target,
      payload,
      status: 'pending',
      created_at: new Date().toISOString(),
      started_at: null,
      completed_at: null,
      verification: null,
      error: null
    };

    this.tasks.push(task);
    this.emit('task_enqueued', task);
    if (this.io) {
      this.io.emit('browser:task_enqueued', task);
    }

    if (!this.isProcessing) {
      this.processQueue();
    }

    return task;
  }

  async processQueue() {
    if (this.isProcessing || this.tasks.length === 0) return;
    this.isProcessing = true;

    while (this.tasks.length > 0) {
      const task = this.tasks.shift();
      this.currentTask = task;
      task.status = 'running';
      task.started_at = new Date().toISOString();

      this.emit('task_started', task);
      if (this.io) {
        this.io.emit('browser:task_started', task);
      }

      try {
        const result = await this._executeTask(task);
        task.status = 'completed';
        task.completed_at = new Date().toISOString();
        task.result = result;

        this.emit('task_completed', task);
        if (this.io) {
          this.io.emit('browser:task_completed', task);
        }
      } catch (err) {
        task.status = 'failed';
        task.error = err.message;
        task.completed_at = new Date().toISOString();

        this.emit('task_failed', task);
        if (this.io) {
          this.io.emit('browser:task_failed', task);
        }
      } finally {
        this.history.push(task);
        this.currentTask = null;
      }
    }

    this.isProcessing = false;
  }

  async _executeTask(task) {
    const { action, payload } = task;

    switch (action) {
      case 'open_studio':
        return await this.studio.openStudio(payload.channelUrl);

      case 'upload_video':
        return await this.studio.selectVideo(payload.videoPath);

      case 'enter_title':
        return await this.studio.enterTitle(payload.title);

      case 'enter_description':
        return await this.studio.enterDescription(payload.description);

      case 'upload_thumbnail':
        return await this.studio.uploadThumbnail(payload.thumbnailPath);

      case 'set_audience':
        return await this.studio.setAudience(payload.madeForKids);

      case 'enter_tags':
        return await this.studio.enterTags(payload.tags);

      case 'navigate_visibility':
        return await this.studio.navigateToVisibility();

      case 'finalize_publish':
        return await this.studio.finalizePublish(payload);

      default:
        throw new Error(`Unknown browser action: ${action}`);
    }
  }

  /**
   * Helper to queue the complete video publishing package generated by all agents
   */
  queueFullPublishWorkflow(projectData) {
    const {
      videoPath,
      title,
      description,
      thumbnailPath,
      tags = [],
      madeForKids = false,
      visibility = 'PUBLIC',
      requireConfirmation = false,
      dryRun = false
    } = projectData;

    this.studio.setDryRun(dryRun);

    this.addTask('agent-manager', 'open_studio', 'youtube_studio', {});
    if (videoPath) {
      this.addTask('agent-video-gen', 'upload_video', 'file_uploader', { videoPath });
    }
    if (title) {
      this.addTask('agent-seo', 'enter_title', 'youtube_title', { title });
    }
    if (description) {
      this.addTask('agent-scriptwriter', 'enter_description', 'youtube_description', { description });
    }
    if (thumbnailPath) {
      this.addTask('agent-seo', 'upload_thumbnail', 'thumbnail_picker', { thumbnailPath });
    }
    this.addTask('agent-manager', 'set_audience', 'audience_picker', { madeForKids });
    if (tags && tags.length > 0) {
      this.addTask('agent-seo', 'enter_tags', 'tags_input', { tags });
    }
    this.addTask('agent-manager', 'navigate_visibility', 'stepper', {});
    this.addTask('agent-manager', 'finalize_publish', 'publish_button', {
      visibility,
      requireConfirmation,
      dryRun
    });
  }

  confirmPublish(confirmed = true) {
    return this.studio.confirmPublish(confirmed);
  }

  getQueueStatus() {
    return {
      isProcessing: this.isProcessing,
      currentTask: this.currentTask,
      queuedCount: this.tasks.length,
      tasks: this.tasks,
      recentHistory: this.history.slice(-15)
    };
  }
}

module.exports = AgentBrowserTaskQueue;
